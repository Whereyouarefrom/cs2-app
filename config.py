# с контракта и т.д.), поэтому для всех них одна и та же двухкомпонентная
# схема отчислений рефереру:
#   REF_LOSS_COMMISSION_PERCENT — % от суммы ПРОИГРЫША реферала за раунд
#       (staked - returned, когда returned < staked — включая кейс, где
#       цена выпавшего скина ниже цены кейса, и проигранную ставку в
#       мини-игре/Апгрейдере/Контракте).
#   REF_WIN_COMMISSION_PERCENT  — % от ЧИСТОГО ВЫИГРЫША реферала за раунд
#       (returned - staked, когда returned > staked, т.е. только "навар",
#       а не вся сумма возврата целиком).
# Обе начисляются рефереру напрямую в balance + в ref_earnings_total, как
