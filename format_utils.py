# ============================================
# Общие хелперы форматирования — используются и в bot.py, и в main.py,
# чтобы баланс везде показывался одинаково.
# ============================================

import math


def format_balance(value: float | int, decimals: int = 2) -> str:
    """Форматирует баланс БЕЗ округления вверх — просто отбрасывает лишние
    знаки после запятой (усечение / truncate), в отличие от round()/f-строк
    вида {value:.2f}, которые округляют по правилам "банковского" округления
    и могут показать 2003.235 как 2003.24 или даже 2003.996 как 2004.00.

    Примеры:
        format_balance(2003.2356) -> "2003.23"
        format_balance(2003.999)  -> "2003.99"   (НЕ 2004.00!)
        format_balance(500)       -> "500.00"
        format_balance(0.004)     -> "0.00"

    Разделители тысяч не добавляются намеренно — точное число важнее
    красивого форматирования; если понадобится группировка разрядов,
    её нужно добавлять отдельно, не трогая логику усечения.
    """
    try:
        num = float(value)
    except (TypeError, ValueError):
        num = 0.0

    if num != num:  # NaN
        num = 0.0

    factor = 10 ** decimals
    # math.trunc всегда отбрасывает дробную часть в сторону нуля —
    # никогда не округляет вверх, в отличие от round()
    truncated = math.trunc(num * factor) / factor

    return f"{truncated:.{decimals}f}"


def format_balance_with_icon(value: float | int, decimals: int = 2) -> str:
    """То же самое, но сразу с иконкой кристалла — для текстов сообщений бота."""
    return f"{format_balance(value, decimals)} 💎"
